/* ============================================================
   js/detail.js — 화면 4(단계별 안내) + 화면 5(보여주기 카드)
   주인: 화면4·5 담당. 이 파일만 고친다.

   화면 4가 풀어야 하는 것:
     - 호출이 필요한 차는 "부르는 방법 3가지"를 나란히 (앱 / 전화 / 정류장 호출벨)
       → 부산 타바라는 앱 예약제였고, 앱을 못 쓰는 사람은 탈 수 없었다.
     - 반대편 정류장 이름이 다르면 큰 경고. 외국인이 가장 많이 하는 실수.
   화면 5:
     - 글자 아주 크게, 전체화면. 말이 안 통할 때 기사님께 그냥 보여준다.
   ============================================================ */

(function () {
  var 앱 = window.하모길;

  /* ---------- 화면 4. 단계별 안내 ---------- */
  앱.화면.안내 = {
    제목: "가는 방법",
    그리기: function (칸) {
      var 경로 = 앱.상태.고른경로;
      if (!경로) {
        칸.innerHTML = '<div class="아직"><h2>고른 경로가 없습니다</h2>' +
          '<button class="큰단추" data-이동="검색">길찾기부터 →</button></div>';
        return;
      }

      var html = '<div class="카드"><div class="크게">' + 앱.esc(경로.이름 || 경로.id) + "</div>" +
        '<div>' + 앱.배지(앱.경로확신도(경로), 앱.말(앱.경로확신도(경로))) + "</div></div>";

      (경로.단계 || []).forEach(function (s, i) {
        html += '<div class="카드"><div class="크게">' + (i + 1) + ". " + 단계제목(s) + "</div>";

        if (s.종류 === "버스") {
          var 노선 = 앱.노선(s.노선) || {};
          var 승 = 앱.정류장(s.승차_id), 하 = 앱.정류장(s.하차_id);
          html += "<p>" + 앱.esc(앱.정류장이름(승)) + " → " + 앱.esc(앱.정류장이름(하)) + "</p>";

          // 막힐 수 있는 곳
          if (노선.저상 && 노선.저상.값 === false) html += '<span class="막힘">' + 앱.esc(앱.말("저상버스 아님")) + "</span>";
          if (노선.저상 && 노선.저상.값 === null) html += 앱.배지("모름", "저상 여부 모름");
          if (노선.저상) html += " " + 앱.배지(노선.저상.확신도, 앱.말(노선.저상.확신도));
          if (노선.저상 && 노선.저상.출처) html += '<p class="작게">출처: ' + 앱.esc(노선.저상.출처) + "</p>";

          // 반대편 정류장 이름 경고
          if (승 && 승.반대편_이름_다름 === true) {
            html += '<p class="막힘">⚠ ' + 앱.esc(앱.말("반대편 정류장 이름 다름")) +
              (승.반대편_id ? " — " + 앱.esc(앱.정류장이름(앱.정류장(승.반대편_id))) : "") + "</p>";
          }

          // 호출이 필요하면 부르는 방법 3가지
          if (노선.호출필요 && 노선.호출필요.값 === true) html += 호출3가지(노선);
        } else if (s.종류 === "도보") {
          html += "<p>" + 앱.esc(s.설명 || "걷기") +
            (s.거리m ? " · " + s.거리m + "m" : "") + "</p>";
          if (s.거리m && s.거리m >= 200) html += '<span class="막힘">' + 앱.esc(앱.말("도보")) + " " + s.거리m + "m</span>";
        }

        html += "<p class='작게'>" + (s.분 === null || s.분 === undefined
          ? "❓ 걸리는 시간 모름" : "약 " + s.분 + 앱.esc(앱.말("분"))) + "</p></div>";
      });

      html += '<button class="큰단추" data-이동="카드">🪧 기사님께 보여주기</button>' +
        '<button class="큰단추 보조" data-이동="제보">이 정보가 틀렸나요?</button>';

      칸.innerHTML = html;   // data-이동 단추는 app.js 가 알아서 잡는다
    }
  };

  function 단계제목(s) {
    if (s.종류 === "버스") return 앱.esc(s.노선) + 앱.말("번") + " 타기";
    if (s.종류 === "도보") return 앱.말("도보");
    if (s.종류 === "호출") return "부르기";
    return 앱.esc(s.종류);
  }

  function 호출3가지(노선) {
    return '<div style="margin-top:10px">' +
      '<p class="크게" style="font-size:18px">부르는 방법 — 셋 중 하나</p>' +
      '<div class="카드" style="margin:6px 0"><b>① 앱</b><p class="작게">스마트폰이 있어야 합니다</p></div>' +
      '<div class="카드" style="margin:6px 0"><b>② 전화</b><p class="크게">1866-1241</p>' +
        '<p class="작게">⚠️ 이 번호는 부산 타바라 기준입니다. 진주 번호는 확인 필요 — ' + 앱.배지("모름", "진주 번호 모름") + "</p></div>" +
      '<div class="카드" style="margin:6px 0"><b>③ 정류장 호출벨</b>' +
        "<p class='작게'>" + 앱.배지("모름", "설치 위치 모름") + "</p></div>" +
      "</div>";
  }

  /* ---------- 화면 5. 보여주기 카드 ---------- */
  앱.화면.카드 = {
    제목: "보여주기",
    그리기: function (칸) {
      var 상 = 앱.상태;
      var 경로 = 상.고른경로;
      var 버스 = 경로 && (경로.단계 || []).filter(function (s) { return s.종류 === "버스"; })[0];
      var 하차 = 버스 ? 앱.정류장(버스.하차_id) : 앱.정류장(상.도착);

      var 아이콘 = "";
      if (상.내조건.indexOf("휠체어") >= 0) 아이콘 += "🦽";
      if (상.내조건.indexOf("유아차") >= 0) 아이콘 += "👶";
      if (상.내조건.indexOf("큰 짐·캐리어") >= 0) 아이콘 += "🧳";
      if (상.내조건.indexOf("지팡이·천천히") >= 0) 아이콘 += "🐢";

      칸.innerHTML =
        '<div class="보여주기" id="보여주기">' +
          '<div class="작게">' + 앱.esc(앱.말("버스 기사님께 보여주세요")) + "</div>" +
          (아이콘 ? '<div class="아이콘들">' + 아이콘 + "</div>" : "") +
          '<div class="문장">' +
            (하차 ? 앱.esc(하차.이름) : "목적지 미정") + "<br>" +
            '<span style="font-size:.7em">' + 앱.esc(앱.말("내려요")) + "</span>" +
          "</div>" +
          (하차 && 하차.이름_ja ? '<div class="흐림">' + 앱.esc(하차.이름_ja) + " / " + 앱.esc(하차.이름_en || "") + "</div>" : "") +
          '<button class="큰단추 보조" id="닫기" style="max-width:280px">닫기</button>' +
        "</div>";

      var 닫기 = 칸.querySelector("#닫기");
      if (닫기) 닫기.onclick = function () { 앱.이동(경로 ? "안내" : "검색"); };
    }
  };

})();
